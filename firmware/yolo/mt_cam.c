/*
 * mt_cam.c -- live camera demo.
 *
 * Two things run on the same 32x32 thumbnail:
 *
 *   1. a brightest-block tracker (pure C, roughly a millisecond): it finds the
 *      brightest 80x80 region of the picture and draws the green box there.
 *      This is what the audience sees, and its behaviour is obvious: the box
 *      sits on the brightest spot.
 *
 *   2. the INT8 detector on the accelerator, every DET_EVERY frames: it shows
 *      that the camera pixels really do reach miniTensor and that its answer
 *      comes back through the same memory.  Its box would be meaningless on a
 *      real scene (the model was fitted on synthetic white squares), so it is
 *      printed rather than drawn.
 */
#include <stdint.h>
#include "ares_soc.h"
#include "mt.h"
#include "mt_net.h"
#include "mt_detect.h"
#include "mt_detect_weights.h"
#include "stereo.h"

#define CAM_PIX_BASE 0xD0002000u
#define CAM_FRAME    0xD0003000u
#define CAM_WRCNT    0xD0003004u
#define CAM_DBG      0xD0003008u
#define OSD_BOX_BASE 0xD0004000u     /* x0, y0, x1, y1, commit */
#define OSD_TEXT_BASE 0xD0005000u    /* 8 glyph indices (7-segment font) */

/* Glyph indices generated by tools/mkfont.py: 0..9 digits, '-' space ':' '.' */
#define GLYPH_SPACE 11u
#define GLYPH_COLON 12u

/* Run the accelerator once every this many frames.  Each run costs ~268 ms,
 * so this is the knob between "smooth green box" and "frequent detector
 * output": 3 gives roughly 11 box updates/s and a detector line every 0.27 s. */
#define DET_EVERY 3

/* Crop the thumbnail below this block average (relative to the frame mean)
 * counts as "nothing bright in view". */
#define TRACK_MARGIN 8u

#define DET_WT_OFF_L1   0x0000u
#define DET_WT_OFF_L2   0x0120u
#define DET_WT_OFF_L3   0x05A0u
#define DET_WT_OFF_L4   0x0EA0u
#define DET_BIAS_OFF_L1 0x000u
#define DET_BIAS_OFF_L2 0x080u
#define DET_BIAS_OFF_L3 0x180u
#define DET_BIAS_OFF_L4 0x280u
#define DET_CFG_OFF_L1  0x00u
#define DET_CFG_OFF_L2  0x10u
#define DET_CFG_OFF_L3  0x20u
#define DET_CFG_OFF_L4  0x30u

#ifdef CAM_DEBUG
static volatile uint32_t cam_raw[4];
#endif

static volatile uint8_t *const buf8 = (volatile uint8_t *)(uintptr_t)MT_BUF_BASE;

static uint8_t rd8(uint32_t off) { return buf8[off]; }

/* Same readback for the second camera (0xD000_6000 window, stereo bring-up). */
static uint32_t cam2_grab(uint8_t *dst)
{
    uint32_t frame;

    for (;;) {
        uint32_t f0 = ARES_MMIO32(0xD000A000u);
        uint32_t i;

        for (i = 0; i < 1024u; i++) {
            uint32_t p;

            (void)ARES_MMIO32(0xD0006000u + i * 4u);   /* address phase */
            p = ARES_MMIO32(0xD0006000u + i * 4u) & 0xFFFFu;
            uint32_t r = ((p >> 11) & 0x1Fu) << 3;
            uint32_t g = ((p >> 5) & 0x3Fu) << 2;
            uint32_t b = (p & 0x1Fu) << 3;

            dst[i * 4u + 0u] = (uint8_t)(r >> 1);
            dst[i * 4u + 1u] = (uint8_t)(g >> 1);
            dst[i * 4u + 2u] = (uint8_t)(b >> 1);
            dst[i * 4u + 3u] = 0;
        }

        frame = ARES_MMIO32(0xD000A000u);
        if (frame == f0) return frame;
    }
}

/* One 32x32 RGB565 thumbnail -> NET_IMAGE, 4-channel layout, channel 0 = luma. */
static uint32_t cam_grab(uint8_t *dst)
{
    uint32_t frame;

    for (;;) {
        uint32_t f0 = ARES_MMIO32(CAM_FRAME);
        uint32_t i;

        for (i = 0; i < 1024u; i++) {
            (void)ARES_MMIO32(CAM_PIX_BASE + i * 4u);
            uint32_t p = ARES_MMIO32(CAM_PIX_BASE + i * 4u);
#ifdef CAM_DEBUG
            if (i < 4u) cam_raw[i] = p;
#endif
            p &= 0xFFFFu;

            uint32_t r = ((p >> 11) & 0x1Fu) << 3;
            uint32_t g = ((p >> 5) & 0x3Fu) << 2;
            uint32_t b = (p & 0x1Fu) << 3;


            /* The trained model looks at colour, so the three channels carry
             * the actual R, G, B instead of a luma value. */
            /* The accelerator's operands are signed bytes, so the 0..255 camera
             * value is halved into 0..127; the packed input scale assumes the
             * same convention (calibration images are divided the same way). */
            dst[i * 4u + 0u] = (uint8_t)(r >> 1);
            dst[i * 4u + 1u] = (uint8_t)(g >> 1);
            dst[i * 4u + 2u] = (uint8_t)(b >> 1);
            dst[i * 4u + 3u] = 0;
        }

        frame = ARES_MMIO32(CAM_FRAME);
        if (frame == f0) return frame;
    }
}

/* Brightest 4x4 block of the thumbnail (one eighth of the crop on each axis),
 * plus the frame mean for the "is anything actually bright" test. */
static void track_bright(const uint8_t *img, int *bx, int *by,
                         uint32_t *bavg, uint32_t *mean, uint32_t *rr,
                         uint32_t *gg, uint32_t *bb)
{
    uint32_t total = 0, best = 0;
    int i, j, yy, xx;

    for (i = 0; i < 1024; i++) total += img[i * 4u];
    *mean = total / 1024u;

    *bx = 0; *by = 0; *bavg = 0;
    *rr = 0; *gg = 0; *bb = 0;

    for (j = 0; j < 8; j++) {
        for (i = 0; i < 8; i++) {
            uint32_t acc = 0;
            for (yy = 0; yy < 4; yy++)
                for (xx = 0; xx < 4; xx++)
                    acc += img[((uint32_t)(j * 4 + yy) * 32u +
                                (uint32_t)(i * 4 + xx)) * 4u];
            if (acc > best) {
                uint32_t sr = 0, sg = 0, sb = 0;

                best  = acc;
                *bx   = i;
                *by   = j;
                *bavg = acc / 16u;
                /* Mean colour of the winning block: the quickest way to see
                 * whether the camera really delivers R/G/B in that order. */
                for (yy = 0; yy < 4; yy++)
                    for (xx = 0; xx < 4; xx++) {
                        uint32_t off = ((uint32_t)(j * 4 + yy) * 32u +
                                        (uint32_t)(i * 4 + xx)) * 4u;
                        sr += img[off + 0u];
                        sg += img[off + 1u];
                        sb += img[off + 2u];
                    }
                *rr = sr / 16u;
                *gg = sg / 16u;
                *bb = sb / 16u;
            }
        }
    }
}

/* "n vv" on screen: how many targets the model found and the strongest cell
 * score, so the readout matches what the boxes show. */
static void publish_text(int count, int peak)
{
    uint32_t v[8];
    int i;

    v[0] = (uint32_t)count;
    v[1] = GLYPH_SPACE;
    v[2] = (uint32_t)((peak / 10) % 10);
    v[3] = (uint32_t)(peak % 10);
    v[4] = GLYPH_SPACE;
    v[5] = GLYPH_SPACE;
    v[6] = GLYPH_SPACE;
    v[7] = GLYPH_SPACE;

    for (i = 0; i < 8; i++)
        ares_mmio_write(OSD_TEXT_BASE + (uint32_t)i * 4u, v[i]);
}

/* Publish up to four boxes.  A box is drawn while x1 > x0, so hiding one is
 * just writing zeros.  The commit write flips the toggle the OSD syncs to. */
static void publish_boxes(int n, const int *px, const int *py)
{
    int i;

    for (i = 0; i < 4; i++) {
        uint32_t off = OSD_BOX_BASE + (uint32_t)i * 16u;
        uint32_t x0 = 0u, y0 = 0u;

        if (i < n) {
            x0 = (uint32_t)(320 + px[i] * 80);
            y0 = (uint32_t)(40 + py[i] * 80);
        }
        ares_mmio_write(off + 0u, x0);
        ares_mmio_write(off + 4u, y0);
        ares_mmio_write(off + 8u, x0 + 80u);
        ares_mmio_write(off + 12u, y0 + 80u);
    }
    ares_mmio_write(OSD_BOX_BASE + 0x40u, 1u);
}

/* Peak picking on the 8x8 object map: take the strongest cell, blank its 3x3
 * neighbourhood, repeat.  Adjacent cells of one object therefore collapse into
 * a single box. */
#define PEAK_MIN 20

static int pick_peaks(const int8_t *m, int *px, int *py, int maxn)
{
    int8_t work[64];
    int i, k, n = 0;

    for (i = 0; i < 64; i++) work[i] = m[i];

    for (k = 0; k < maxn; k++) {
        int best = -128, bi = -1;
        int dy, dx;

        for (i = 0; i < 64; i++)
            if (work[i] > best) { best = work[i]; bi = i; }
        if (bi < 0 || best < PEAK_MIN) break;

        px[n] = bi & 7;
        py[n] = bi >> 3;
        n++;

        for (dy = -1; dy <= 1; dy++)
            for (dx = -1; dx <= 1; dx++) {
                int yy = py[n - 1] + dy, xx = px[n - 1] + dx;
                if (yy >= 0 && yy < 8 && xx >= 0 && xx < 8)
                    work[yy * 8 + xx] = -128;
            }
    }
    return n;
}

/* Multi-object state: the last set of peaks, kept for a few frames so a
 * missed detection does not make every box blink at once. */
static int    hold_px[4], hold_py[4], hold_n = 0;
static int    lost_n = 0;
static int8_t obj_map[64];

static void run_detector(net_layer_t *L, uint32_t frame, uint32_t *cmds)
{
    int32_t sum = 0, sy = 0, sx = 0;
    int gy, gx;
    uint32_t start = mt_rd_mcycle();
    uint32_t hot = 0, dma_stall, busy, p0d, p0b;

    /* The counters are free running, so snapshot and subtract. */
    p0d = ARES_MMIO32(0xE0000018u);
    p0b = ARES_MMIO32(0xE000001Cu);

    net_pad(&L[0]);
    if (net_conv(&L[0], cmds) != 0) { printf("layer1 error\n"); return; }
    net_pool2(MT_BUF_BASE, OUT_BUF, MID_BUF, 2u, 32u, 32u, 0u, 0u);

    net_pad(&L[1]);
    if (net_conv(&L[1], cmds) != 0) { printf("layer2 error\n"); return; }
    net_pool2(MT_BUF_BASE, OUT_BUF, MID_BUF, 4u, 16u, 16u, 0u, 0u);

    net_pad(&L[2]);
    if (net_conv(&L[2], cmds) != 0) { printf("layer3 error\n"); return; }

    net_pad(&L[3]);
    if (net_conv(&L[3], cmds) != 0) { printf("layer4 error\n"); return; }

    for (gy = 0; gy < 8; gy++) {
        for (gx = 0; gx < 8; gx++) {
            int8_t v = (int8_t)rd8(MID_BUF + (((uint32_t)gy * 8u +
                                               (uint32_t)gx) * 4u));
            obj_map[gy * 8 + gx] = v;
            if (v > 0) { sum += v; sy += v * gy; sx += v * gx; }
        }
    }

    hot       = mt_rd_mcycle() - start;
    dma_stall = ARES_MMIO32(0xE0000018u) - p0d;
    busy      = ARES_MMIO32(0xE000001Cu) - p0b;

    {
        int px[4], py[4];
        int n = pick_peaks(obj_map, px, py, 4);

        if (n > 0) {
            int i;
            lost_n = 0;
            for (i = 0; i < n; i++) { hold_px[i] = px[i]; hold_py[i] = py[i]; }
            hold_n = n;
            publish_text(n, obj_map[py[0] * 8 + px[0]] & 0x7F);
            publish_boxes(n, px, py);
            printf("  net: %d target(s) at (%d,%d)", n, px[0], py[0]);
            if (n > 1) printf(" (%d,%d)", px[1], py[1]);
            if (n > 2) printf(" (%d,%d)", px[2], py[2]);
            if (n > 3) printf(" (%d,%d)", px[3], py[3]);
            printf(" t=%u busy=%u\n", (unsigned)hot, (unsigned)busy);
        } else if (hold_n > 0 && lost_n < 6) {
            /* brief dropouts: keep the last set instead of blinking out */
            lost_n++;
            publish_boxes(hold_n, hold_px, hold_py);
            printf("  net: hold %d target(s) t=%u busy=%u\n",
                   hold_n, (unsigned)hot, (unsigned)busy);
        } else {
            hold_n = 0;
            publish_text(0, 0);
            publish_boxes(0, px, py);
            printf("  net: no detection t=%u busy=%u\n",
                   (unsigned)hot, (unsigned)busy);
        }
    }
}

/* ---------------------------------------------------------------- G5: range
 * Reads a 64x64 region from each eye through the MMIO windows and reports the
 * distance to whatever is in it.
 *
 * The windows hand out one pixel per read and take two reads each (address
 * phase, then data), so a 64x64 left plus 88x64 right region costs about
 * 19k bus accesses -- roughly 7 ms, which is why the region is small.
 */
#define ST_L_BASE   0xD0100000u
#define ST_R_BASE   0xD0150000u
#define ROI_X0      88          /* default; find_texture() overrides it */
#define ROI_Y0      72
#define ROI_W       96
#define ROI_H       64

static uint8_t roi_l[ROI_W * ROI_H];
static uint8_t roi_r[(ROI_W + ST_DMAX) * ROI_H];

static void read_roi(uint32_t base, int x0, int y0, int w, int h, uint8_t *dst)
{
    int x, y;

    for (y = 0; y < h; y++) {
        for (x = 0; x < w; x++) {
            uint32_t addr = base + (uint32_t)((y0 + y) * ST_W + (x0 + x)) * 4u;

            // One read is enough: the window's state machine already waits the
            // two cycles the frame memory needs.  A second read here returned
            // zeros (the extra request landed while the bus was still busy).
            dst[y * w + x] = (uint8_t)(ARES_MMIO32(addr) & 0xFFu);
        }
    }
}

/* "1.50 172" on the text row: distance in metres, height in centimetres. */
static void publish_metrics(uint32_t mm, uint32_t height_cm)
{
    uint32_t cm = mm / 10u;
    uint32_t v[8];
    int i;

    v[0] = (cm / 100u) % 10u;
    v[1] = 13u;                       /* separator dot */
    v[2] = (cm / 10u) % 10u;
    v[3] = cm % 10u;
    v[4] = GLYPH_SPACE;
    v[5] = (height_cm / 100u) % 10u;
    v[6] = (height_cm / 10u) % 10u;
    v[7] = height_cm % 10u;

    for (i = 0; i < 8; i++)
        ares_mmio_write(OSD_TEXT_BASE + (uint32_t)i * 4u, v[i]);
}

/* ---------------------------------------------------------- G7: height
 * Background subtraction on a 40x30 grid of the same 320x240 crop the stereo
 * pair uses (one sample per 8x8 cell), so the silhouette and the distance refer
 * to the same field of view.  The camera is fixed and the wall is static, which
 * is exactly the case where this beats any learned detector on cost.
 */
#define BG_W 40
#define BG_H 30
#define BG_T 14           /* per-cell luma difference that counts as "subject" */

static uint8_t bg[BG_W * BG_H];
static uint8_t cur[BG_W * BG_H];

static void sample_grid(uint8_t *dst)
{
    int x, y;

    for (y = 0; y < BG_H; y++)
        for (x = 0; x < BG_W; x++)
            dst[y * BG_W + x] = (uint8_t)(ARES_MMIO32(ST_L_BASE +
                (uint32_t)((y * 8) * ST_W + (x * 8)) * 4u) & 0xFFu);
}

static void bg_capture(void)
{
    int k, i;

    for (i = 0; i < BG_W * BG_H; i++) bg[i] = 0;

    for (k = 0; k < 8; k++) {
        sample_grid(cur);
        for (i = 0; i < BG_W * BG_H; i++)
            bg[i] = (uint8_t)((bg[i] + cur[i]) / 2);   /* running mean */
    }
}

/* One character from the serial port, or -1.  'c' re-captures the background. */
static int uart_poll(void)
{
    if (ARES_MMIO32(UART_STATUS) & 2u) return (int)(ARES_MMIO32(UART_BASE) & 0xFFu);
    return -1;
}

/* Tallest vertical run of "subject" cells; returns its pixel height (each cell
 * is 8 pixels of the 240 line image). */
/* Object = what differs from the background.  The camera is fixed and the wall
 * is static, so this gives a solid box (not just an outline) and costs one
 * subtraction per cell.  The background is captured at boot, or on demand by
 * sending 'c' over the serial port -- remove the object, send 'c', put it back.
 *
 * Per-cell differences are taken relative to the frame mean, because
 * auto-exposure shifts the whole picture.
 */
static int find_object(int *ox0, int *oy0, int *ox1, int *oy1)
{
    static uint8_t seen[BG_W * BG_H];
    static int16_t stack[BG_W * BG_H];
    uint8_t diff[BG_W * BG_H];
    uint32_t dsum = 0;
    int mean, i, best_area = 0;
    int bx0 = 0, by0 = 0, bx1 = 0, by1 = 0;

    for (i = 0; i < BG_W * BG_H; i++) {
        int d = (int)cur[i] - (int)bg[i];
        if (d < 0) d = -d;
        if (d > 255) d = 255;
        diff[i] = (uint8_t)d;
        dsum += (uint32_t)d;
        seen[i] = 0;
    }
    mean = (int)(dsum / (BG_W * BG_H));

    for (i = 0; i < BG_W * BG_H; i++) {
        int sp = 0, area = 0;
        int x0 = BG_W, y0 = BG_H, x1 = 0, y1 = 0;

        if (seen[i] || (int)diff[i] - mean <= BG_T) continue;

        stack[sp++] = (int16_t)i;
        seen[i] = 1;
        while (sp > 0) {
            int c = stack[--sp];
            int cx = c % BG_W, cy = c / BG_W;
            int dy, dx;

            area++;
            if (cx < x0) x0 = cx;
            if (cx > x1) x1 = cx;
            if (cy < y0) y0 = cy;
            if (cy > y1) y1 = cy;

            for (dy = -1; dy <= 1; dy++)
                for (dx = -1; dx <= 1; dx++) {
                    int nx = cx + dx, ny = cy + dy, ni;
                    if (nx < 0 || ny < 0 || nx >= BG_W || ny >= BG_H) continue;
                    ni = ny * BG_W + nx;
                    if (!seen[ni] && (int)diff[ni] - mean > BG_T) {
                        seen[ni] = 1;
                        stack[sp++] = (int16_t)ni;
                    }
                }
        }

        if (area > best_area) {
            best_area = area;
            bx0 = x0; by0 = y0; bx1 = x1; by1 = y1;
        }
    }

    if (best_area < 6) return 0;

    *ox0 = bx0 * 8;
    *oy0 = by0 * 8;
    *ox1 = bx1 * 8 + 7;
    *oy1 = by1 * 8 + 7;
    return 1;
}

/* Pick the most textured 64x64 tile of the frame, so the demo does not depend on
 * where the interesting object happens to be.  Samples every 8th pixel (40x24),
 * scores 5x3 tiles by variance and returns the winner's top-left corner. */
static void find_texture(int *ox, int *oy)
{
    uint8_t s[40 * 24];
    int x, y, best = -1, bx = 1, by = 1;

    for (y = 0; y < 24; y++)
        for (x = 0; x < 40; x++)
            s[y * 40 + x] = (uint8_t)(ARES_MMIO32(ST_L_BASE +
                (uint32_t)((y * 10) * ST_W + (x * 8)) * 4u) & 0xFFu);

    for (y = 0; y < 3; y++)
        for (x = 0; x < 5; x++) {
            uint32_t sum = 0, sum2 = 0;
            int i, j, n = 0, score;

            for (j = 0; j < 8; j++)
                for (i = 0; i < 8; i++) {
                    uint32_t v = s[(y * 8 + j) * 40 + (x * 8 + i)];
                    sum += v;
                    sum2 += v * v;
                    n++;
                }
            score = (int)(sum2 / (uint32_t)n - (sum / (uint32_t)n) * (sum / (uint32_t)n));
            if (score > best) { best = score; bx = x; by = y; }
        }

    *ox = bx * 64 + 32 - ROI_W / 2;
    *oy = by * 64 + 32 - ROI_H / 2;
    if (*ox < 0) *ox = 0;
    if (*oy < 0) *oy = 0;
    if (*ox > ST_W - ROI_W) *ox = ST_W - ROI_W;
    if (*oy > ST_H - ROI_H) *oy = ST_H - ROI_H;
}

/* Vertical extent of what sits at the measured disparity.  For each row of the
 * 320x240 image, compare a few samples of the left eye with the right eye at the
 * disparity that won, and keep the longest run of rows that agree.  This ties the
 * height to the same measurement as the distance, so no background model is
 * involved.
 */
static int extent_at_depth(int32_t d_q4, int x0, int w, int *oy0, int *oy1)
{
    int d = (int)((d_q4 + 2) / 4);
    int y, k, run = 0, best = 0, besty0 = 0, besty1 = 0, cury0 = 0;

    if (d < 1) return 0;

    for (y = 0; y < ST_H; y++) {
        int cost = 0, n2 = 0;

        for (k = 0; k < w; k += 4) {
            int x = x0 + k;
            uint32_t la = ST_L_BASE + (uint32_t)(y * ST_W + x) * 4u;
            uint32_t ra = ST_R_BASE + (uint32_t)(y * ST_W + (x - d)) * 4u;
            int lv = (int)(ARES_MMIO32(la) & 0xFFu);
            int rv = (int)(ARES_MMIO32(ra) & 0xFFu);
            cost += (lv > rv) ? (lv - rv) : (rv - lv);
            n2++;
        }
        cost = n2 ? cost / n2 : 99;

        if (cost < 18) {
            if (run == 0) cury0 = y;
            run++;
            if (run > best) { best = run; besty0 = cury0; besty1 = y; }
        } else {
            run = 0;
        }
    }
    if (best < 16) return 0;
    *oy0 = besty0;
    *oy1 = besty1;
    return best;
}

int yolo_camera_run(void)
{
    uint32_t frames = 0, t0 = 0;

    printf("object range: %dx%d texture ROI, f=%d px, baseline %d mm\n",
           ROI_W, ROI_H, ST_F_PX, ST_BASELINE_MM);
    ares_mmio_write(ARES_LED_ADDR, 1u);
    t0 = mt_rd_mcycle();

    for (;;) {
        int n = 0, ox = ROI_X0, oy = ROI_Y0;
        int ty0 = 0, ty1 = 0;
        int32_t d_q4;
        uint32_t z_mm = 0, h_cm = 0;
        int ch;

        /* 'c' re-learns the empty scene (kept although the tracker no longer
         * needs it: it is the cheapest way to check lighting drift). */
        ch = uart_poll();
        if (ch == 'c' || ch == 'C') {
            bg_capture();
            printf("background captured\n");
        }

        /* the stereo window follows the most textured tile */
        find_texture(&ox, &oy);
        read_roi(ST_L_BASE, ox, oy, ROI_W, ROI_H, roi_l);
        read_roi(ST_R_BASE, ox - ST_DMAX, oy,
                 ROI_W + ST_DMAX, ROI_H, roi_r);

        d_q4 = st_match_roi_step(roi_l, ROI_W, roi_r, ROI_W + ST_DMAX,
                                 0, 0, ROI_W, ROI_H, 32, &n);
        if (d_q4 > 0) z_mm = st_depth_mm(d_q4);

        /* and the height is the vertical run that sits at the same depth */
        if (d_q4 > 0 && extent_at_depth(d_q4, ox, ROI_W, &ty0, &ty1)) {
            int v_px = ty1 - ty0 + 1;
            uint32_t h_mm = (uint32_t)(((uint64_t)z_mm * (uint32_t)v_px) / ST_F_PX);

            h_cm = h_mm / 10u;

            ares_mmio_write(OSD_BOX_BASE + 0u,  (uint32_t)(320 + ox * 2));
            ares_mmio_write(OSD_BOX_BASE + 4u,  (uint32_t)(80 + ty0 * 2));
            ares_mmio_write(OSD_BOX_BASE + 8u,  (uint32_t)(320 + (ox + ROI_W) * 2));
            ares_mmio_write(OSD_BOX_BASE + 12u, (uint32_t)(80 + ty1 * 2));
            ares_mmio_write(OSD_BOX_BASE + 0x40u, 1u);

            if ((frames & 0x07u) == 0u)
                printf("object x=%d..%d y=%d..%d v_px=%d d_q4=%d z=%u h=%u\n",
                       ox, ox + ROI_W - 1, ty0, ty1, v_px, (int)d_q4,
                       (unsigned)z_mm, (unsigned)h_cm);
        } else {
            ares_mmio_write(OSD_BOX_BASE + 0u, 0u);
            ares_mmio_write(OSD_BOX_BASE + 4u, 0u);
            ares_mmio_write(OSD_BOX_BASE + 8u, 0u);
            ares_mmio_write(OSD_BOX_BASE + 12u, 0u);
            ares_mmio_write(OSD_BOX_BASE + 0x40u, 1u);
            if ((frames & 0x07u) == 0u) {
                int ax, ay;
                printf("no measurement (d_q4=%d, blocks=%d); field:\n", (int)d_q4, n);
                for (ay = 0; ay < 24; ay++) {
                    char row[42];
                    for (ax = 0; ax < 40; ax++) {
                        uint32_t addr = ST_L_BASE +
                            (uint32_t)((ay * 10) * ST_W + (ax * 8)) * 4u;
                        uint32_t v = ARES_MMIO32(addr) & 0xFFu;
                        row[ax] = (v > 140) ? '#' : (v > 90 ? '+' : (v > 45 ? '.' : ' '));
                    }
                    row[40] = 0;
                    printf("|%s|\n", row);
                }
            }
        }

        publish_metrics(z_mm, h_cm);

        frames++;
        if ((frames & 3u) == 0u) {
            uint32_t el = mt_rd_mcycle() - t0;
            printf("  %u frames, %u cyc/frame\n",
                   (unsigned)frames, (unsigned)(el / frames));
        }
    }
    return 0;
}
