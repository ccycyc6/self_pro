#!/usr/bin/env python3
"""Generate rtl/video/video_font.v -- a 7-segment style 8x8 font.

Only the glyphs the demo needs are generated (digits, space, colon, dot, dash),
and they are built from a segment table rather than hand-drawn, so the shapes
are guaranteed to be legible.

    segment layout inside the 8x8 cell

        aaaa            row 0, cols 1..6
      f      b          rows 1..3, col 0 / col 7
      f      b
        gggg            row 4, cols 1..6
      e      c          rows 5..7, col 0 / col 7
      e      c
        dddd            row 7, cols 1..6
"""
from pathlib import Path

SEGS = {
    '0': "abcdef", '1': "bc", '2': "abged", '3': "abgcd", '4': "fgbc",
    '5': "afgcd", '6': "afgecd", '7': "abc", '8': "abcdefg", '9': "abcdfg",
    '-': "g", ' ': "",
}

def glyph(ch):
    rows = [0] * 8
    segs = SEGS.get(ch, "")
    def setpx(r, c):
        rows[r] |= 1 << (7 - c)
    if 'a' in segs:
        for c in range(1, 7): setpx(0, c)
    if 'f' in segs:
        for r in range(1, 4): setpx(r, 0)
    if 'b' in segs:
        for r in range(1, 4): setpx(r, 7)
    if 'g' in segs:
        for c in range(1, 7): setpx(4, c)
    if 'e' in segs:
        for r in range(5, 8): setpx(r, 0)
    if 'c' in segs:
        for r in range(5, 8): setpx(r, 7)
    if 'd' in segs:
        for c in range(1, 7): setpx(7, c)
    if ch == ':':
        for r in (2, 5):
            setpx(r, 3); setpx(r, 4)
    if ch == '.':
        setpx(7, 3); setpx(7, 4)
    return rows

CHARS = "0123456789- :."
out = []
out.append("// Generated by tools/mkfont.py -- do not edit by hand.")
out.append("`timescale 1ns/1ps")
out.append("//")
out.append("// video_font: 8x8 glyph ROM for the OSD text layer.  Only digits and the")
out.append("// few symbols the demo needs are stored, so the ROM is a small case rather")
out.append("// than a 1 KiB table.")
out.append("module video_font (")
out.append("    input  wire [4:0] ch,      // character index into CHARS")
out.append("    input  wire [2:0] row,     // 0..7 within the glyph")
out.append("    output reg  [7:0] bits     // bit 7 = leftmost pixel")
out.append(");")
out.append("    always @(*) begin")
out.append("        case ({ch, row})")
for i, c in enumerate(CHARS):
    for r, v in enumerate(glyph(c)):
        out.append("            8'd%d: bits = 8'h%02X;   // '%s' row %d" % (i * 8 + r, v, c, r))
out.append("            default: bits = 8'h00;")
out.append("        endcase")
out.append("    end")
out.append("endmodule")
Path("rtl/video/video_font.v").write_text("".join(line + chr(10) for line in out))
print("wrote rtl/video/video_font.v with", len(CHARS), "glyphs")
